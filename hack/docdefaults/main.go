// Command docdefaults generates the FlowCollector defaults reference from the
// in-code flowslatest.DefaultFlowCollector, so that the documented defaults can
// never drift from the ones the controller actually applies.
//
// The shipped CRDs deliberately carry no OpenAPI defaults (see the comment on
// DefaultFlowCollector): defaulting happens in the controller instead, so that a
// minimal FlowCollector stays minimal once applied. That keeps the resource
// readable but hides the defaults from the CRD-derived API reference, which this
// file makes up for.
//
// It also annotates the crdoc-generated API references with a note pointing at
// that file, since they would otherwise show no defaults at all.
//
// Usage: docdefaults <output.md> [<api-reference.md>...]
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"sigs.k8s.io/yaml"

	flowslatest "github.com/netobserv/netobserv-operator/api/flowcollector/v1beta2"
)

const header = `<!-- Code generated by hack/docdefaults. DO NOT EDIT. -->

# FlowCollector default values

These are the values the NetObserv operator applies when the corresponding fields are
not set in the ` + "`FlowCollector`" + ` resource.

Unlike OpenAPI defaults, they are applied in memory during reconciliation and are
**not** written back into the resource: a minimal ` + "`FlowCollector`" + ` stays minimal once
applied. Anything you do set always takes precedence.

See [FlowCollector.md](./FlowCollector.md) for the full API reference.

` + "```yaml\n"

// Anchors in the crdoc output: the note goes under the top-level FlowCollector
// heading, just before its field table.
const (
	heading     = "## FlowCollector"
	tableAnchor = "<table>"
	noteMarker  = "[FlowCollector default values]"
)

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: docdefaults <output.md> [<api-reference.md>...]")
		os.Exit(1)
	}
	defaults := os.Args[1]
	if err := run(defaults); err != nil {
		fmt.Fprintln(os.Stderr, "docdefaults:", err)
		os.Exit(1)
	}
	for _, doc := range os.Args[2:] {
		if err := annotate(doc, defaults); err != nil {
			fmt.Fprintln(os.Stderr, "docdefaults:", fmt.Errorf("%s: %w", doc, err))
			os.Exit(1)
		}
		fmt.Printf("docdefaults: annotated %s\n", doc)
	}
}

// annotate inserts a pointer to the defaults reference into a crdoc-generated
// API reference, which cannot show defaults itself because they are not in the
// CRD schema.
func annotate(docPath, defaultsPath string) error {
	raw, err := os.ReadFile(docPath)
	if err != nil {
		return err
	}
	content := string(raw)
	if strings.Contains(content, noteMarker) {
		// crdoc rewrites the file on every run, so this only triggers when the
		// tool is run twice without regenerating; keep it idempotent anyway.
		return nil
	}
	rel, err := filepath.Rel(filepath.Dir(docPath), defaultsPath)
	if err != nil {
		return err
	}

	lines := strings.Split(content, "\n")
	insertAt := -1
	seenHeading := false
	for i, line := range lines {
		switch {
		case line == heading:
			seenHeading = true
		case seenHeading && line == tableAnchor:
			insertAt = i
		}
		if insertAt >= 0 {
			break
		}
	}
	if insertAt < 0 {
		return fmt.Errorf("could not find %q followed by %q", heading, tableAnchor)
	}

	note := []string{
		"> [!NOTE]",
		"> Default values are not shown in this reference. Unlike OpenAPI defaults, they are not",
		"> part of the CRD schema: the operator applies them in memory during reconciliation and",
		"> does not write them back, so a minimal `FlowCollector` stays minimal once applied.",
		"> Anything you set explicitly always takes precedence.",
		fmt.Sprintf("> See [FlowCollector default values](%s) for the complete list.", filepath.ToSlash(rel)),
		"",
	}

	out := make([]string, 0, len(lines)+len(note))
	out = append(out, lines[:insertAt]...)
	out = append(out, note...)
	out = append(out, lines[insertAt:]...)
	return os.WriteFile(docPath, []byte(strings.Join(out, "\n")), 0o644)
}

func run(path string) error {
	// Round-trip through JSON so that the output honours the API's json tags,
	// matching what a user would actually write in the resource.
	b, err := json.Marshal(flowslatest.DefaultFlowCollector)
	if err != nil {
		return err
	}
	var spec map[string]interface{}
	if err := json.Unmarshal(b, &spec); err != nil {
		return err
	}

	pruned, _ := prune(spec)
	out, err := yaml.Marshal(map[string]interface{}{
		"apiVersion": flowslatest.GroupVersion.String(),
		"kind":       "FlowCollector",
		"metadata":   map[string]interface{}{"name": "cluster"},
		"spec":       pruned,
	})
	if err != nil {
		return err
	}

	return os.WriteFile(path, []byte(header+string(out)+"```\n"), 0o644)
}

// prune drops zero values. They show up only because some API fields lack the
// `omitempty` json tag and so always marshal; they are not real defaults. A zero
// default would in any case be a no-op, since EnsureDefaults cannot distinguish
// it from an unset field.
func prune(v interface{}) (interface{}, bool) {
	switch t := v.(type) {
	case nil:
		return nil, false
	case string:
		return t, t != ""
	case bool:
		return t, t
	case float64:
		return t, t != 0
	case []interface{}:
		return t, len(t) > 0
	case map[string]interface{}:
		out := make(map[string]interface{}, len(t))
		for k, sub := range t {
			if p, keep := prune(sub); keep {
				out[k] = p
			}
		}
		return out, len(out) > 0
	}
	return v, true
}
