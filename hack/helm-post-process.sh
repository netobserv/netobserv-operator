#!/usr/bin/env bash

depl=helm/templates/apps_v1_deployment_netobserv-controller-manager.yaml

# Using perl rather than sed for regex substitution here, more portable with multi-line replacement

# Operator image
perl -i -pe "
  s|^([[:space:]]*)image: .*/$IMAGE_ORG/network-observability-operator:.*$|{{- if .Values.operator.digest }}
\${1}image: \"{{ .Values.operator.image }}\@{{ .Values.operator.digest }}\"
{{- else }}
\${1}image: \"{{ .Values.operator.image }}:{{ .Values.operator.version }}\"
{{- end }}|
" $depl
grep -q 'operator.digest' $depl || { echo "ERROR: Operator substitution had no match for '/$IMAGE_ORG/network-observability-operator:'"; exit 1; }

# eBPF agent image
perl -i -pe '
  s|^([[:space:]]*)value: .*/netobserv/netobserv-ebpf-agent:.*$|{{- if .Values.ebpfAgent.digest }}
${1}value: "{{ .Values.ebpfAgent.image }}\@{{ .Values.ebpfAgent.digest }}"
{{- else }}
${1}value: "{{ .Values.ebpfAgent.image }}:{{ .Values.ebpfAgent.version }}"
{{- end }}|
' $depl
grep -q 'ebpfAgent.digest' $depl || { echo "ERROR: Agent substitution had no match for '/netobserv/netobserv-ebpf-agent:'"; exit 1; }

# FLP image
perl -i -pe '
  s|^([[:space:]]*)value: .*/netobserv/flowlogs-pipeline:.*$|{{- if .Values.flowlogsPipeline.digest }}
${1}value: "{{ .Values.flowlogsPipeline.image }}\@{{ .Values.flowlogsPipeline.digest }}"
{{- else }}
${1}value: "{{ .Values.flowlogsPipeline.image }}:{{ .Values.flowlogsPipeline.version }}"
{{- end }}|
' $depl
grep -q 'flowlogsPipeline.digest' $depl || { echo "ERROR: FLP substitution had no match for '/netobserv/flowlogs-pipeline:'"; exit 1; }

# Web console image
perl -i -pe '
  s|^([[:space:]]*)value: .*/netobserv/network-observability-console-plugin:.*$|{{- if .Values.standaloneConsole.enable }}
  {{- if .Values.standaloneConsole.digest }}
${1}value: "{{ .Values.standaloneConsole.image }}\@{{ .Values.standaloneConsole.digest }}"
  {{- else }}
${1}value: "{{ .Values.standaloneConsole.image }}:{{ .Values.standaloneConsole.version }}"
  {{- end }}
{{- else }}
  {{- if .Values.consolePlugin.digest }}
${1}value: "{{ .Values.consolePlugin.image }}\@{{ .Values.consolePlugin.digest }}"
  {{- else }}
${1}value: "{{ .Values.consolePlugin.image }}:{{ .Values.consolePlugin.version }}"
  {{- end }}
{{- end }}|
' $depl
grep -q 'standaloneConsole.digest' $depl || { echo "ERROR: Web console substitution had no match for '/netobserv/network-observability-console-plugin:'"; exit 1; }

# Affinity
perl -i -pe '
  s/^([[:space:]]*)affinity: .*$/{{- if .Values.operator.nodeAffinity }}
${1}affinity:
${1}  nodeAffinity:
{{- toYaml .Values.operator.nodeAffinity | nindent 10 }}
{{- end }}/
' $depl
grep -q 'operator.nodeAffinity' $depl || { echo "ERROR: affinity substitution had no match for 'affinity:'"; exit 1; }

# -0777 makes perl read the whole file, for multi-line match
perl -0777 -i -pe '
  s|^([ ]*)- name: OPERATOR_NETWORK_POLICY\n[ ]*value: "true"$|${1}- name: OPERATOR_NETWORK_POLICY
${1}  value: "{{ .Values.operator.installNetworkPolicy }}"|gm
' $depl
grep -q 'operator.installNetworkPolicy' $depl || { echo "ERROR: Network policy substitution had no match for 'OPERATOR_NETWORK_POLICY'"; exit 1; }

grep 'quay.io/netobserv' $depl && { echo "ERROR: Some image substitution seem missing, 'quay.io/netobserv' still found in the deployment"; exit 1; }

{
  echo "# This file is generated by Kustomize and helm-post-process.sh -- DO NOT EDIT."
  cat "$depl"
} > "$depl.tmp" && mv "$depl.tmp" "$depl"

# Edit CRDs
for crd in helm/templates/apiextensions.k8s.io_v1_customresourcedefinition_*; do
  perl -i -pe 's/(`[^`]*\{\{[^`]*`)/{{\1}}/g' $crd # escape "{{" for helm
done

# Cert-manager related files must check if enabled
cert_mngr_files=$(grep -l "cert-manager.io/inject" helm/templates/*)
for f in $cert_mngr_files; do
  {
    echo "# This file is generated by Kustomize and modified by helm-post-process.sh -- DO NOT EDIT."
    echo "{{ if .Values.certManager.enable }}"
    cat helm/templates/$(basename "$f")
    echo "{{ end }}"
  } > "$f.tmp" && mv "$f.tmp" helm/templates/$(basename "$f")
done

# Copy static files
cp helm/static/NOTES.txt helm/templates/
for f in helm/static/*.yaml; do
  cp "$f" helm/templates/
  {
    echo "# File copied from $f by helm-post-process.sh -- DO NOT EDIT."
    cat helm/templates/$(basename "$f")
  } > "$f.tmp" && mv "$f.tmp" helm/templates/$(basename "$f")
done

cp LICENSE helm/
